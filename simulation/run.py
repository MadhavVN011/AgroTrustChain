"""Run the WTH-Raft experiments and write simulation/results/.

    python simulation/run.py            # full run (about a minute)
    python simulation/run.py --quick    # small run, used by CI

Writes performance.csv, byzantine.csv, latency.png, throughput.png,
byzantine.png, byzantine_sleeper.png and RESULTS.md. The run is deterministic: same code, same numbers.
"""
import argparse
import csv
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))

from wthraft import byzantine, network  # noqa: E402
from wthraft.reputation import PARAMS  # noqa: E402

HERE = os.path.dirname(os.path.abspath(__file__))

# Fixed colour per protocol in every chart (validated categorical palette, light mode).
COLORS = {"WTH-Raft": "#2a78d6", "Raft": "#eb6834", "PBFT": "#1baf7a", "Two-hop (unweighted)": "#eda100"}
MARKERS = {"WTH-Raft": "o", "Raft": "s", "PBFT": "^", "Two-hop (unweighted)": "D"}
SURFACE, INK, MUTED, GRID = "#fcfcfb", "#1f1f1e", "#6b6a66", "#e4e3df"
PAPER_SUCCESS_CLAIM = 94.0


def run_performance(sizes, samples):
    rows = []
    for n in sizes:
        for protocol in network.PROTOCOLS:
            s = max(3, samples // 3) if protocol == "PBFT" and n >= 100 else samples
            m = network.measure(protocol, n, s)
            rows.append({"protocol": protocol, "nodes": n, "latency_ms": round(m["latency_ms"], 2),
                         "tps": round(m["tps"], 1), "messages_per_tx": round(m["messages"])})
    return rows


def run_byzantine(n, fractions, rounds, trials):
    rows = []
    for strategy in ("always", "sleeper"):
      for b in fractions:
        for protocol, r in byzantine.success_rates(n, b, rounds, trials, strategy).items():
            rows.append({"strategy": strategy, "protocol": protocol, "nodes": n, "malicious_fraction": b,
                         "success_pct": round(100 * r["success"], 1),
                         "success_during_attack_pct": round(100 * r["success_during_attack"], 1),
                         "success_first_10_attack_rounds_pct": round(100 * r["success_first_10_attack_rounds"], 1),
                         "malicious_weight_share_pct": round(100 * r["malicious_weight_share"], 1),
                         "honest_suspended_avg": round(r["honest_suspended"], 2),
                         "malicious_suspended_avg": round(r["malicious_suspended"], 2)})
    return rows


def write_csv(path, rows):
    with open(path, "w", newline="") as file:
        writer = csv.DictWriter(file, fieldnames=list(rows[0].keys()))
        writer.writeheader()
        writer.writerows(rows)


def _style(ax, title, xlabel, ylabel):
    ax.set_facecolor(SURFACE)
    ax.set_title(title, loc="left", color=INK, fontsize=12, fontweight="bold", pad=12)
    ax.set_xlabel(xlabel, color=MUTED)
    ax.set_ylabel(ylabel, color=MUTED)
    ax.grid(True, color=GRID, linewidth=0.8)
    ax.set_axisbelow(True)
    for side in ("top", "right"):
        ax.spines[side].set_visible(False)
    for side in ("left", "bottom"):
        ax.spines[side].set_color(GRID)
    ax.tick_params(colors=MUTED)


def _line_chart(rows, x_key, y_key, protocols, path, title, xlabel, ylabel, log=False, reference=None):
    import matplotlib
    matplotlib.use("Agg")
    import matplotlib.pyplot as plt

    fig, ax = plt.subplots(figsize=(8, 4.6), dpi=150)
    fig.patch.set_facecolor(SURFACE)
    _style(ax, title, xlabel, ylabel)
    if log:
        ax.set_yscale("log")
    if reference:
        value, label = reference
        ax.axhline(value, color=MUTED, linewidth=1, linestyle=(0, (4, 3)), label=label)
    for protocol in protocols:
        points = [(r[x_key], r[y_key]) for r in rows if r["protocol"] == protocol]
        xs, ys = zip(*points)
        ax.plot(xs, ys, color=COLORS[protocol], linewidth=2, marker=MARKERS[protocol], markersize=6,
                markeredgecolor=SURFACE, markeredgewidth=1.5, label=protocol)
        ax.annotate(protocol, (xs[-1], ys[-1]), xytext=(8, 0), textcoords="offset points",
                    color=INK, fontsize=9, va="center")
    ax.legend(frameon=False, loc="upper left", bbox_to_anchor=(0, -0.14), ncol=min(3, len(protocols) + bool(reference)),
              labelcolor=INK, fontsize=9)
    ax.margins(x=0.12)
    fig.tight_layout()
    fig.savefig(path, facecolor=SURFACE)
    plt.close(fig)


def _pct(a, b):
    return 100.0 * (b - a) / a


def write_results(perf, byz, byz_nodes, args, path):
    by = {(r["protocol"], r["nodes"]): r for r in perf}
    sizes = sorted({r["nodes"] for r in perf})
    big = [n for n in sizes if n >= 50]

    lines = ["# WTH-Raft simulation results", "",
             "Generated by `python simulation/run.py%s`. Do not edit by hand: re-run the script." % (" --quick" if args.quick else ""),
             "See [README.md](README.md) for the model and its assumptions.", ""]

    # Paper claims vs this simulation.
    reductions = {n: _pct(by[("Raft", n)]["latency_ms"], by[("WTH-Raft", n)]["latency_ms"]) for n in sizes}
    # Smallest size from which WTH-Raft is faster than Raft at every larger size too.
    faster_from = next((n for n in sizes if all(reductions[m] < 0 for m in sizes if m >= n)), None)
    tps_drop = {p: _pct(by[(p, big[0])]["tps"], by[(p, sizes[-1])]["tps"]) for p in network.PROTOCOLS}
    tps_ratio = by[("WTH-Raft", sizes[-1])]["tps"] / by[("Raft", sizes[-1])]["tps"]
    byz20 = {r["protocol"]: r for r in byz if r["strategy"] == "always" and abs(r["malicious_fraction"] - 0.2) < 1e-9}
    sleep20 = {r["protocol"]: r for r in byz if r["strategy"] == "sleeper" and abs(r["malicious_fraction"] - 0.2) < 1e-9}

    lines += ["## The paper's claims, checked", "",
              "| Claim in the paper | This simulation | Verdict |", "| --- | --- | --- |"]
    large = [n for n in sizes if n >= 100]
    red_large = ", ".join("%d%% at %d nodes" % (-reductions[n], n) for n in large)
    slower = [n for n in sizes if faster_from and n < faster_from]
    small_note = ("but it is *slower* than Raft below %d nodes (%+.0f%% at %d nodes), because of the extra hop"
                  % (faster_from, reductions[slower[0]], slower[0])) if slower else "at every size simulated"
    lines.append("| Two-hop cuts consensus latency by about 25-30%% vs flat architectures at scale "
                 "| Lower latency than Raft for large networks: %s; %s | Partly confirmed: the reduction depends on network size |"
                 % (red_large, small_note))
    lines.append("| Throughput stays stable past 50 nodes while Raft and PBFT degrade sharply "
                 "| From %d to %d nodes, TPS changes by %+.0f%% for WTH-Raft, %+.0f%% for Raft, %+.0f%% for PBFT; "
                 "at %d nodes WTH-Raft handles %.1fx Raft's TPS "
                 "| Partly confirmed: WTH-Raft is much faster at every size, but its TPS still falls as the network grows, "
                 "because the work of the leader and each primary grows with the square root of the network size |"
                 % (big[0], sizes[-1], tps_drop["WTH-Raft"], tps_drop["Raft"], tps_drop["PBFT"], sizes[-1], tps_ratio))
    if byz20:
        w = byz20["WTH-Raft"]
        lines.append("| Consensus success above 94%% with 20%% malicious nodes "
                     "| %.1f%% for WTH-Raft (%d nodes), vs %.1f%% Raft, %.1f%% PBFT, %.1f%% unweighted two-hop | %s |"
                     % (w["success_pct"], byz_nodes, byz20["Raft"]["success_pct"], byz20["PBFT"]["success_pct"],
                        byz20["Two-hop (unweighted)"]["success_pct"],
                        ("Confirmed, under the assumptions below" if w["success_pct"] > PAPER_SUCCESS_CLAIM else "Not confirmed")))
    if sleep20:
        w = sleep20["WTH-Raft"]
        lines.append("| (Not in the paper) the same, against sleeper attackers that build reputation first "
                     "| %.1f%% of attack rounds for WTH-Raft (%.1f%% in the first 10), vs %.1f%% Raft, %.1f%% PBFT | "
                     "WTH-Raft still holds, because honest nodes keep most of the weight |"
                     % (w["success_during_attack_pct"], w["success_first_10_attack_rounds_pct"],
                        sleep20["Raft"]["success_during_attack_pct"], sleep20["PBFT"]["success_during_attack_pct"]))
    lines += ["",
              "Two-hop does not reduce the *total* number of messages (%d per transaction at %d nodes for both Raft and WTH-Raft). "
              "It spreads them over the primaries, so no single node, especially the leader, has to send and process them all."
              % (by[("Raft", sizes[-1])]["messages_per_tx"], sizes[-1]), ""]

    lines += ["## Latency and throughput", "", "![Latency](latency.png)", "", "![Throughput](throughput.png)", "",
              "| Nodes | " + " | ".join("%s latency (ms)" % p for p in network.PROTOCOLS) + " | "
              + " | ".join("%s TPS" % p for p in network.PROTOCOLS) + " |",
              "| --- " * (1 + 2 * len(network.PROTOCOLS)) + "|"]
    for n in sizes:
        lines.append("| %d | " % n + " | ".join("%.1f" % by[(p, n)]["latency_ms"] for p in network.PROTOCOLS) + " | "
                     + " | ".join("%.1f" % by[(p, n)]["tps"] for p in network.PROTOCOLS) + " |")

    lines += ["", "**The key assumption** behind the Byzantine results: after every round, an off-chain inspection "
              "reveals the truth, and the contract scores every node's report against it. Real inspections are "
              "slower, sampled and themselves fallible. With a weaker oracle, malicious nodes would keep their weight "
              "for longer, and the results would move towards the unweighted two-hop line.", ""]
    for strategy, title, image in (("always", "attackers lie every round", "byzantine.png"),
                                   ("sleeper", "sleeper attackers: honest for the first half, then all lie", "byzantine_sleeper.png")):
        lines += ["## Byzantine resilience: %s (%d nodes)" % (title, byz_nodes), "", "![%s](%s)" % (title, image), "",
                  "| Malicious nodes | Protocol | Success, all rounds | Success, attack rounds | Success, first 10 attack rounds | Malicious share of weight at end | Honest nodes wrongly suspended (avg) | Malicious nodes suspended (avg) |",
                  "| --- | --- | --- | --- | --- | --- | --- | --- |"]
        for r in (r for r in byz if r["strategy"] == strategy):
            weighted = r["protocol"] == "WTH-Raft"
            lines.append("| %d%% | %s | %.1f%% | %.1f%% | %.1f%% | %s | %s | %s |" % (
                round(100 * r["malicious_fraction"]), r["protocol"], r["success_pct"], r["success_during_attack_pct"],
                r["success_first_10_attack_rounds_pct"],
                ("%.1f%%" % r["malicious_weight_share_pct"]) if weighted else "n/a (unweighted)",
                r["honest_suspended_avg"] if weighted else "n/a", r["malicious_suspended_avg"] if weighted else "n/a"))
        lines.append("")
    lines += ["",
              "*Two-hop (unweighted)* is an ablation, not a protocol from the paper: it is WTH-Raft's structure with "
              "one node, one vote. It shows how much of WTH-Raft's resilience comes from the weighting.", "",
              "Reputation parameters (the same as the contract's defaults): " + ", ".join("%s = %s" % kv for kv in PARAMS.items()) + ".",
              "Run settings: %d samples per point (PBFT at 100+ nodes: %d), %d rounds x %d trials per Byzantine point."
              % (args.samples, max(3, args.samples // 3), args.rounds, args.trials), ""]
    with open(path, "w") as file:
        file.write("\n".join(lines))


def main():
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--quick", action="store_true", help="small run for CI")
    parser.add_argument("--out", default=os.path.join(HERE, "results"))
    args = parser.parse_args()
    if args.quick:
        sizes, args.samples, args.rounds, args.trials, fractions, byz_nodes = [10, 50, 100], 3, 60, 3, [0.0, 0.2], 50
    else:
        sizes, args.samples, args.rounds, args.trials = [7, 10, 25, 50, 75, 100, 150, 200], 30, 200, 20
        fractions, byz_nodes = [0.0, 0.1, 0.2, 0.3, 0.4], 100

    os.makedirs(args.out, exist_ok=True)
    perf = run_performance(sizes, args.samples)
    byz = run_byzantine(byz_nodes, fractions, args.rounds, args.trials)
    write_csv(os.path.join(args.out, "performance.csv"), perf)
    write_csv(os.path.join(args.out, "byzantine.csv"), byz)

    perf_protocols = ["WTH-Raft", "Raft", "PBFT"]
    _line_chart(perf, "nodes", "latency_ms", perf_protocols, os.path.join(args.out, "latency.png"),
                "Consensus latency by network size", "Nodes", "Latency per transaction (ms)")
    _line_chart(perf, "nodes", "tps", perf_protocols, os.path.join(args.out, "throughput.png"),
                "Throughput by network size", "Nodes", "Transactions per second (log scale)", log=True)
    for strategy, image, title in (("always", "byzantine.png", "Consensus success, attackers lie every round (%d nodes)"),
                                   ("sleeper", "byzantine_sleeper.png", "Consensus success during a sleeper attack (%d nodes)")):
        rows = [dict(r, malicious_pct=round(100 * r["malicious_fraction"])) for r in byz if r["strategy"] == strategy]
        y_key = "success_pct" if strategy == "always" else "success_during_attack_pct"
        _line_chart(rows, "malicious_pct", y_key, byzantine.PROTOCOLS, os.path.join(args.out, image),
                    title % byz_nodes, "Malicious nodes (%)", "Rounds decided correctly (%)",
                    reference=(PAPER_SUCCESS_CLAIM, "Paper's claim: 94% success at 20% malicious"))
    write_results(perf, byz, byz_nodes, args, os.path.join(args.out, "RESULTS.md"))
    print("Wrote results to", args.out)


if __name__ == "__main__":
    main()
